import { createHash } from "node:crypto";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

import ts from "typescript";

const repositoryRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const pluginRoot = resolve(repositoryRoot, "plugins/ai-booster-kit");
const checkOnly = process.argv.slice(2).includes("--check");
const unexpected = process.argv.slice(2).filter((value) => value !== "--check");

if (unexpected.length > 0) {
  process.stderr.write("Usage: node scripts/package-booster-plugin.mjs [--check]\n");
  process.exitCode = 4;
} else {
  const files = await expectedFiles();
  const stale = [];

  for (const file of files) {
    let actual = null;
    try {
      actual = await readFile(file.destination, "utf8");
    } catch (error) {
      if (error?.code !== "ENOENT") throw error;
    }

    if (actual === file.content) continue;
    stale.push(file.label);
    if (!checkOnly) {
      await mkdir(dirname(file.destination), { recursive: true });
      await writeFile(file.destination, file.content, "utf8");
    }
  }

  if (checkOnly && stale.length > 0) {
    process.stdout.write(`${JSON.stringify({ status: "NOT_READY", stale })}\n`);
    process.exitCode = 2;
  } else {
    process.stdout.write(`BOOSTER_PACKAGE=READY files=${files.length}${stale.length > 0 ? ` updated=${stale.length}` : ""}\n`);
  }
}

async function expectedFiles() {
  const compassSourcePath = resolve(repositoryRoot, "src/booster/compass.ts");
  const compassSource = await readFile(compassSourcePath, "utf8");
  const transpiled = ts.transpileModule(compassSource, {
    compilerOptions: {
      target: ts.ScriptTarget.ES2022,
      module: ts.ModuleKind.ES2022,
      newLine: ts.NewLineKind.LineFeed,
      removeComments: false,
    },
    fileName: compassSourcePath,
    reportDiagnostics: true,
  });
  const errors = (transpiled.diagnostics ?? []).filter((diagnostic) => diagnostic.category === ts.DiagnosticCategory.Error);
  if (errors.length > 0) {
    throw new Error(`Compass transpilation failed: ${errors.map((diagnostic) => diagnostic.messageText).join("; ")}`);
  }
  const sourceHash = createHash("sha256").update(compassSource, "utf8").digest("hex");
  const compassRuntime = [
    "// Generated by scripts/package-booster-plugin.mjs. Do not edit directly.",
    `// Source: src/booster/compass.ts sha256:${sourceHash}`,
    transpiled.outputText.trimEnd(),
    "",
  ].join("\n");

  const files = [
    {
      label: "scripts/booster-compass.mjs",
      destination: resolve(pluginRoot, "scripts/booster-compass.mjs"),
      content: compassRuntime,
    },
    await copiedFile("LICENSE", "LICENSE"),
    await copiedFile("contract/booster/skill-registry.json", "registry/skill-registry.json"),
    await transformedFile(
      "skills/planning-show/SKILL.md",
      "skills/planning-show/SKILL.md",
      removeClaudeOnlyFrontmatter,
    ),
    await transformedFile(
      "skills/planning-show/SKILL.md",
      "claude-skills/planning-show/SKILL.md",
      adaptClaudeSkill,
    ),
    await copiedFile("skills/planning-show/agents/openai.yaml", "skills/planning-show/agents/openai.yaml"),
  ];

  for (const skillId of [
    "ai-booster-kit",
    "booster-team-align",
    "booster-implement",
    "booster-test",
    "booster-review",
    "booster-handoff",
  ]) {
    files.push(await transformedFile(
      `plugins/ai-booster-kit/skills/${skillId}/SKILL.md`,
      `claude-skills/${skillId}/SKILL.md`,
      adaptClaudeSkill,
    ));
  }

  return files;
}

async function copiedFile(sourceRelative, destinationRelative) {
  return {
    label: destinationRelative,
    destination: resolve(pluginRoot, destinationRelative),
    content: await readFile(resolve(repositoryRoot, sourceRelative), "utf8"),
  };
}

async function transformedFile(sourceRelative, destinationRelative, transform) {
  const source = await readFile(resolve(repositoryRoot, sourceRelative), "utf8");
  return {
    label: destinationRelative,
    destination: resolve(pluginRoot, destinationRelative),
    content: transform(source),
  };
}

function removeClaudeOnlyFrontmatter(source) {
  return source.replace(/^disable-model-invocation: true\r?\n/mu, "");
}

function addClaudeOnlyFrontmatter(source) {
  if (/^disable-model-invocation:/mu.test(source)) return source;
  const closing = source.indexOf("\n---\n", 4);
  if (closing < 0) throw new Error("Skill source is missing closing frontmatter");
  return `${source.slice(0, closing)}\ndisable-model-invocation: true${source.slice(closing)}`;
}

function adaptClaudeSkill(source) {
  let adapted = addClaudeOnlyFrontmatter(source)
    .replace(
      /- Start only from an explicit `\$ai-booster-kit` request in Codex or the\r?\n  namespaced `\/ai-booster-kit:ai-booster-kit` Skill in Claude Code\./u,
      "- Start only from an explicit `/ai-booster-kit:ai-booster-kit` request in Claude Code.",
    )
    .replace(
      "- Start only from an explicit `/planning-show` or `$planning-show` request.",
      "- Start only from an explicit `/ai-booster-kit:planning-show` request.",
    );
  for (const skillId of [
    "ai-booster-kit",
    "planning-show",
    "booster-team-align",
    "booster-implement",
    "booster-test",
    "booster-review",
    "booster-handoff",
  ]) {
    adapted = adapted.replaceAll(`$${skillId}`, `/ai-booster-kit:${skillId}`);
  }
  return adapted.replaceAll("/planning-show", "/ai-booster-kit:planning-show");
}
